def body_len(text):
    body = text.split('## 本章状态更新')[0]
    return len(re.sub(r'\s', '', body))

def find_chapter_file(num):
    for f in os.listdir(BASE):
        if f.startswith(f'第{num}章'):
            return os.path.join(BASE, f)
    return None

def main():
    for num, expansion in EXPANSIONS.items():
        path = find_chapter_file(num)
        if not path:
            print(f'{num}: NOT FOUND')
            continue
        with open(path, 'r', encoding='utf-8') as f:
            content = f.read()
        before = body_len(content)
        if before >= 3000:
            print(f'{num}: already OK ({before})')
            continue
        marker = '\n## 本章状态更新'
        if marker not in content:
            print(f'{num}: no marker')
            continue
        exp = expansion.strip()
        if not exp.startswith('*'):
            exp = '\n' + exp
        new_content = content.replace(marker, '\n' + exp + '\n\n* * *\n' + marker, 1)
        after = body_len(new_content)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(new_content)
        print(f'{num}: {before} -> {after} ({after - before:+d})')

    # fix ch34 Russian word
    p34 = find_chapter_file('034')
    if p34:
        with open(p34, 'r', encoding='utf-8') as f:
            c = f.read()
        if 'метафора' in c:
            c = c.replace('钉不是 метафора，是稳态锁的实体', '钉不是譬喻，是稳态锁的实体')
            with open(p34, 'w', encoding='utf-8') as f:
                f.write(c)
            print('034: fixed foreign word')

if __name__ == '__main__':
    main()
